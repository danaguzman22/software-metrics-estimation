CREATE TABLE defectos (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id              text NOT NULL,
    descripcion              text NOT NULL CHECK (length(trim(descripcion)) > 0),
    severidad                text NOT NULL CHECK (severidad IN ('Alta', 'Media', 'Baja')),
    estado                   text NOT NULL CHECK (estado IN ('Abierto', 'En curso', 'Resuelto')),
    item_numero              integer NOT NULL,
    sprint_deteccion_numero  integer NOT NULL,
    sprint_resolucion_numero integer,
    CONSTRAINT defectos_item_fk
        FOREIGN KEY (proyecto_id, item_numero)
        REFERENCES items_backlog (proyecto_id, numero),
    CONSTRAINT defectos_sprint_deteccion_fk
        FOREIGN KEY (proyecto_id, sprint_deteccion_numero)
        REFERENCES sprints (proyecto_id, numero),
    CONSTRAINT defectos_sprint_resolucion_fk
        FOREIGN KEY (proyecto_id, sprint_resolucion_numero)
        REFERENCES sprints (proyecto_id, numero),
    CONSTRAINT defectos_resuelto_sprint_check
        CHECK (estado <> 'Resuelto' OR sprint_resolucion_numero IS NOT NULL),
    CONSTRAINT defectos_cronologia_check
        CHECK (sprint_resolucion_numero IS NULL OR sprint_resolucion_numero >= sprint_deteccion_numero)
);

CREATE INDEX defectos_proyecto_id_idx ON defectos (proyecto_id, id);

